"""Minimal typing of the pypdfium2 objects the gates drive (the package is imported by name at run time and is optional,
so there is nothing to import its types from). Only the methods the code calls are listed."""
from __future__ import annotations

from collections.abc import Iterator
from typing import Protocol

from PIL import Image


class PdfiumBitmap(Protocol):
    def to_pil(self) -> Image.Image: ...


class PdfiumTextPage(Protocol):
    def count_chars(self) -> int: ...
    def get_text_range(self) -> str: ...
    def get_charbox(self, index: int, loose: bool = ...) -> tuple[float, float, float, float]: ...


class PdfiumPage(Protocol):
    def get_size(self) -> tuple[float, float]: ...
    def get_textpage(self) -> PdfiumTextPage: ...
    def render(self, scale: float = ..., grayscale: bool = ...) -> PdfiumBitmap: ...


class PdfiumDoc(Protocol):
    def __len__(self) -> int: ...
    def __iter__(self) -> Iterator[PdfiumPage]: ...
    def __getitem__(self, index: int) -> PdfiumPage: ...
    def get_metadata_dict(self) -> dict[str, str]: ...
    def count_attachments(self) -> int: ...
